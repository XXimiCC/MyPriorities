/*
 * Куда ведут ссылки в приложение: в браузер или в Telegram — и с какой меткой.
 *
 * На компьютере правильный ответ — новая вкладка веб-версии: человек
 * рассматривает лендинг, и уводить его со страницы, чтобы он потом искал
 * дорогу назад, невежливо.
 *
 * На телефоне правильный ответ другой. Приложение — мини-апп, и в клиенте
 * Telegram оно и живёт: там есть кнопка «назад», ярлык на домашний экран и
 * аккаунт, которым потом включается синхронизация. Открытая в мобильном
 * Safari вкладка не даёт ничего из этого. Поэтому там ссылка ведёт в бота:
 *
 *   t.me/<бот>/app?startapp=<метка>
 *
 * `startapp` приезжает в приложение через клиент, а не адресной строкой, и
 * разбирается в src/demo/mode.ts и src/sync/source.ts — префикс `demo_` там
 * понимают давно, `from_` появился вместе с этим файлом.
 *
 * Признак телефона — грубый указатель, а не ширина окна: узкое окно на
 * компьютере остаётся компьютером, и Telegram там открывать незачем.
 *
 * ── Метка источника ──────────────────────────────────────────────────────
 *
 * Каталог или статья ведут на лендинг со своей меткой: `mypriorities.life/?from=habr`.
 * Отсюда она уезжает дальше — в `startapp` на телефоне и в `?from=` в браузере, —
 * и приложение доносит её до профиля вместе со входом. Без этого на вопрос
 * «пришёл ли хоть кто-нибудь по этой ссылке» ответить нечем: у человека,
 * открывшего приложение, никакого следа канала не остаётся.
 *
 * Чужих счётчиков здесь нет и не будет: метка едет своим путём, тем же, что и
 * всё остальное в синхронизации.
 */

const COARSE = '(pointer: coarse)';

/** Хвост `startapp`, которым метка отличается от демо-приглашения. */
const START_PREFIX = 'from_';

/** Тот же смысл в адресной строке: `?from=habr`. Имя одно на лендинге и в приложении. */
const PARAM = 'from';

/**
 * Что вообще может быть меткой. Та же форма, что в src/sync/source.ts и в
 * worker/src/auth.ts: значение доезжает до базы и до ночного отчёта, и сужать
 * алфавит дешевле, чем потом экранировать его в трёх местах.
 */
const SHAPE = /^[a-z0-9][a-z0-9_-]{0,31}$/;

/**
 * Метка этого захода.
 *
 * Своей метки в адресе нет — значит человек пришёл на сам лендинг, и канал
 * так и называется. Английская страница отмечается отдельно: язык страницы —
 * это тоже ответ на «откуда», и различать их дешевле сразу, чем гадать потом.
 */
function channel() {
  const asked = (new URLSearchParams(location.search).get(PARAM) || '').trim().toLowerCase();
  if (SHAPE.test(asked)) return asked;
  return document.documentElement.lang === 'en' ? 'site-en' : 'site';
}

/**
 * Дописать параметр к ссылке.
 *
 * Ссылки собраны в разметке метками `{{APP}}` и `{{BOT}}`, и половина из них
 * уже несёт свой запрос (`?demo=f`, `?lang=en`) — поэтому разбор адресом, а не
 * склейка строк: одна лишняя `?` превращает ссылку в мусор молча.
 */
function withParam(url, name, value) {
  const at = new URL(url, location.href);
  at.searchParams.set(name, value);
  return at.toString();
}

const links = document.querySelectorAll('[data-entry]');

if (links.length) {
  const coarse = window.matchMedia(COARSE);
  const tag = channel();

  const apply = () => {
    for (const link of links) {
      const telegram = link.dataset.entryTg;
      const web = link.dataset.entryWeb;
      if (!telegram || !web) continue;

      /*
       * Свой `startapp` у ссылки уже есть — это витрина демо, и там он несёт
       * приглашение посмотреть чужую жизнь. Перебить его меткой значило бы
       * открыть человеку приложение вместо демо, на которое он нажимал;
       * дописать метку рядом нельзя — параметр один. Такие ссылки остаются как
       * есть, обе стороны.
       */
      const own = new URL(telegram, location.href).searchParams.has('startapp');

      if (coarse.matches) {
        link.href = own ? telegram : withParam(telegram, 'startapp', START_PREFIX + tag);
        // В клиент Telegram уходим текущей вкладкой: там своя навигация назад.
        link.removeAttribute('target');
        link.removeAttribute('rel');
      } else {
        link.href = own ? web : withParam(web, PARAM, tag);
        link.target = '_blank';
        link.rel = 'noopener';
      }
    }
  };

  apply();
  // Подключили мышь к планшету — ссылки переобуваются на лету.
  coarse.addEventListener('change', apply);
}
