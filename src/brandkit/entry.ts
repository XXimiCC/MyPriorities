/**
 * Как открыть брендкит.
 *
 * Два пути, и у каждого своя причина:
 *
 *   ?brand в адресе — работает в любой сборке, включая ту, что открыта внутри
 *     Telegram: параметр дописывается к адресу мини-аппа. Это единственный
 *     способ посмотреть систему стилей на настоящем телефоне, а не в браузере
 *     на столе, — а именно там она и живёт.
 *   строка в настройках — только в режиме разработки (import.meta.env.DEV).
 *     В собранном приложении её нет: обычному человеку справочник по классам не
 *     нужен, а лишняя строка в настройках стоит дороже, чем кажется.
 *
 * Признак читается один раз при загрузке модуля, как и режим демо: адресная
 * строка за время сессии не меняется, а пересчитывать её на каждый рендер
 * значило бы делать вид, что меняется.
 */

const PARAM = 'brand';

function resolve(): boolean {
  if (typeof window === 'undefined') return false;
  return new URLSearchParams(window.location.search).has(PARAM);
}

/** Приложение открыто сразу на брендките. */
export const BRAND_ASKED = resolve();

/** Показывать ли строку перехода в настройках. */
export const BRAND_ROW = import.meta.env.DEV;
