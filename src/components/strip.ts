/**
 * Дотянуть нажатый элемент горизонтальной ленты до видимости.
 *
 * Ленты в приложении шире экрана и прокручиваются пальцем — но только пальцем.
 * На большом экране горизонтального жеста нет вовсе: колесо мыши крутит по
 * вертикали, а полосу прокрутки ленты намеренно прячут (она перечёркивала бы
 * ряд). Получалось, что крайние дни видно наполовину и добраться до них нечем.
 *
 * Поэтому лента едет по нажатию. Режим `nearest`, а не `center`: элемент,
 * который и так виден целиком, не двигается совсем — иначе каждый выбор дня
 * дёргал бы всю ленту, хотя человек ничего не просил. Подрезанный краем
 * элемент подтягивается ровно настолько, чтобы стать видимым, и вместе с ним
 * из-за края выходит следующий: лента проходится нажатиями до конца.
 */
export function revealInStrip(node: HTMLElement): void {
  node.scrollIntoView({ inline: 'nearest', block: 'nearest', behavior: 'smooth' });
}
