/**
 * «Сейчас» с точностью до минуты — для экранов, где время идёт само.
 *
 * Заряд считается между отметками, поэтому «в этом состоянии — 1 ч» живёт не в
 * журнале, а во времени: журнал не меняется часами, а число обязано расти. До
 * этого цифры замирали на моменте последней записи и оживали только от смены
 * вкладки — экран, открытый в 9 утра, в полдень показывал девять.
 *
 * Секунды здесь не нужны: всё, что считается по этим часам, измеряется в
 * минутах, а тик раз в секунду — это шестьдесят лишних перерисовок в минуту.
 */

import { useEffect, useState } from 'react';

export function useNow(): Date {
  const [now, setNow] = useState(() => new Date());

  useEffect(() => {
    const refresh = (): void => setNow(new Date());

    /*
     * Ждём границу минуты, а не шестьдесят секунд от монтирования: иначе цифра
     * переключается в случайный момент и расходится с часами на экране. Запас
     * в полсекунды — чтобы таймер, сработавший чуть раньше срока, не прочитал
     * прежнюю минуту и не взвёлся тут же снова.
     */
    const delay = 60_000 - (now.getSeconds() * 1000 + now.getMilliseconds()) + 500;
    const timer = window.setTimeout(refresh, delay);

    /*
     * Возвращение из фона. В свёрнутом мини-аппе таймеры придерживают, и без
     * этого экран показывал бы время ухода до конца текущей минуты — а уходят
     * обычно не на минуту. Сюда же попадает и ночь: за неё меняется день, и
     * сутки на экране переезжают сразу, а не после первого тика.
     */
    const onVisible = (): void => {
      if (document.visibilityState === 'visible') refresh();
    };
    document.addEventListener('visibilitychange', onVisible);

    return () => {
      window.clearTimeout(timer);
      document.removeEventListener('visibilitychange', onVisible);
    };
  }, [now]);

  return now;
}
