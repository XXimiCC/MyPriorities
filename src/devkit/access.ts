/**
 * Показывать ли панель и насколько заметно.
 *
 * Чистая функция от адреса и настроек — потому что «почему панель не
 * открывается» иначе выясняется только на живом телефоне. Правила читаются
 * сверху вниз, и порядок здесь важнее самих правил.
 *
 * Белого списка тут нет и быть не может: список номеров в бандле утёк бы вместе
 * со сборкой, а обойти его в браузере — дело одной строки в консоли. Кто может
 * заводить тикеты, решает сервер (см. worker/src/devkit.ts), и панель
 * спрашивает его сразу при открытии — чтобы отказ пришёл до разметки, а не
 * после. Жест — не защита, а способ не показывать инструмент отладки тем, кому
 * он не нужен.
 */

export type Availability =
  /** Видимая кнопка: своя машина или явно попросили адресом. */
  | 'always'
  /** Только по скрытому жесту. */
  | 'gesture'
  /** Панели нет вовсе. */
  | 'off';

/** Параметр адреса: `?devkit=1` включает, `?devkit=0` выключает. */
const PARAM = 'devkit';

function isOwnMachine(hostname: string): boolean {
  const name = hostname.toLowerCase();
  if (name === 'localhost' || name === '127.0.0.1' || name === '::1' || name === '[::1]') return true;
  if (name.endsWith('.local') || name.endsWith('.localhost')) return true;
  // Домашняя сеть: телефон, открывший dev-сервер по адресу вида 192.168.0.5.
  if (name.startsWith('10.') || name.startsWith('192.168.')) return true;
  const private172 = /^172\.(1[6-9]|2\d|3[01])\./.exec(name);
  return private172 !== null;
}

export function availability(input: {
  endpoint: string;
  hostname: string;
  search: string;
  demo?: boolean;
  /** Ключ из ссылки тестировщика: ему панель показывается кнопкой. */
  invite?: string;
  /** Приложение само попросило показать значок (см. DevkitHost.visible). */
  asked?: boolean;
}): Availability {
  // Некуда слать — панель не просто бесполезна, она обманывает: человек
  // размечает кадр, а отправить его некуда.
  if (!input.endpoint) return 'off';

  const asked = new URLSearchParams(input.search).get(PARAM);

  // Явное «нет» сильнее всего остального: этим параметром съёмка документации
  // (tools/shots/capture.mjs) гарантирует, что панель не попадёт в кадр.
  if (asked === '0') return 'off';

  if (isOwnMachine(input.hostname)) return 'always';

  // Телефон приходит на dev-сервер через туннель со случайным именем, и по
  // имени его от боевого адреса не отличить. Поэтому — явный параметр.
  if (asked === '1') return 'always';

  /* Просьба от самого приложения. В клиенте Telegram на компьютере это
     единственный надёжный путь: адрес не поправить, пальцев нет, а сочетание
     клавиш может забрать себе клиент. */
  if (input.asked) return 'always';

  // В демо панель молчит: приложение показывают другому человеку, а его кадр
  // экрана нам не нужен и отправить его всё равно нечем — входа нет.
  if (input.demo) return 'off';

  /*
   * Приглашённому тестировщику — видимая кнопка. Жест тремя пальцами хорош
   * ровно до того момента, когда помогать зовут другого человека: объяснять
   * его в переписке дороже, чем получить отчёт.
   *
   * Ключ здесь не проверяется — проверить его может только сервер. Панель лишь
   * показывается; чужой ключ означает отказ при отправке, а не тайную кнопку.
   */
  if (input.invite) return 'always';

  return 'gesture';
}
