/**
 * Правило для строки «эта история есть только на этом устройстве».
 *
 * Пока человек не вошёл, его история существует ровно в одном экземпляре — это
 * единственный необратимый сценарий в продукте. Настройки об этом честно
 * говорят строкой «Где хранятся», но настройки открывают один раз в жизни, а
 * история копится месяцами.
 *
 * Правило намеренно узкое. Строка — перебивка на экране, который открыли
 * смотреть на себя, и она оправдана ровно один раз: когда терять уже есть что,
 * а ни копии, ни входа так и не случилось. Дальше она молчит навсегда.
 *
 * Отдельным файлом, а не двумя строками в экране, ради проверяемости: «когда
 * показать» — это условие с четырьмя входами и порогом, и его дешевле держать
 * чистой функцией, чем разбирать глазами в разметке.
 */

import { count } from '../i18n';
import { daysBetween, todayKey } from './date';
import { earliestDay } from './stats';
import type { Journal, Settings } from './types';

/**
 * Сколько дней истории должно накопиться, чтобы об этом стоило говорить.
 *
 * Месяц — тот срок, после которого «начну заново» перестаёт быть ответом на
 * потерю телефона. Раньше — перебивка ради данных, которые не жалко.
 */
export const LOCAL_ONLY_MIN_DAYS = 30;

/**
 * Дней истории: от первой отметки до сегодня, включая оба конца (так считает
 * daysBetween). Ноль — отмечать ещё не начинали.
 */
export function historyDays(journal: Journal, now: Date = new Date()): number {
  const first = earliestDay(journal);
  return first ? daysBetween(first, todayKey(now)) : 0;
}

/**
 * Пора ли сказать. Вход, снятая копия и уже закрытая строка отменяют её
 * одинаково: во всех трёх случаях человек уже знает то, что она сообщает.
 */
export function localOnlyDue(settings: Settings, days: number, signedIn: boolean): boolean {
  if (signedIn || settings.exported || settings.localOnlySeen) return false;
  return days > LOCAL_ONLY_MIN_DAYS;
}

/**
 * Возраст истории словами: «месяц», «4 месяца», «2 года».
 *
 * Дней и недель здесь нет намеренно: ниже месяца строка не показывается вовсе,
 * а округление всегда вниз — «4 месяца» на пятом месяце это факт, «5 месяцев»
 * было бы преувеличением ровно там, где приложение говорит о потере данных.
 */
export function historyAge(days: number): string {
  if (days < 365) return count('month', Math.max(1, Math.floor(days / 30)));
  return count('year', Math.floor(days / 365));
}
