/** Один — 0, два-четыре — 1, остальное — 2. Одиннадцать-четырнадцать всегда 2. */
export function ruPluralIndex(n: number): number {
  const mod100 = Math.abs(n) % 100;
  const mod10 = mod100 % 10;
  if (mod100 >= 11 && mod100 <= 14) return 2;
  if (mod10 === 1) return 0;
  if (mod10 >= 2 && mod10 <= 4) return 1;
  return 2;
}
