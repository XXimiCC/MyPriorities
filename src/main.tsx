/**
 * Точка входа. Всё, что она делает, — выстраивает порядок: сначала SDK
 * Telegram, потом приложение.
 *
 * Порядок и есть смысл этого файла. Выбор хранилища (telegram/cloudStorage.ts),
 * признак isTelegram, регистрация service worker — всё это вычисляется один раз,
 * при выполнении модулей, и обязано увидеть window.Telegram уже готовым.
 * Обычным импортом такого не добиться: импорты выполняются раньше первой строки
 * файла, который их написал. Отсюда динамический import(): он откладывает
 * выполнение всего остального до готовности SDK.
 *
 * Ждать при этом есть чего только внутри клиента Telegram — снаружи
 * loadTelegramSdk() вообще ничего не грузит и отвечает сразу (telegram/load.ts).
 *
 * Стилей здесь нет намеренно: весь каскад живёт в boot.tsx одним куском, потому
 * что граница чанка — это ещё и граница порядка листов.
 */
import { loadTelegramSdk } from './telegram/load';

void loadTelegramSdk().then(async () => {
  const { start } = await import('./boot');
  start();
});
