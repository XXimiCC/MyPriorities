/**
 * Язык интерфейса, выбранный руками, — на этом устройстве.
 *
 * Не в Settings, которые едут на сервер, и это не экономия: настройки
 * поднимаются из IndexedDB асинхронно, а язык нужен ДО первой отрисовки.
 * Иначе приложение показывает один язык и через кадр другой.
 *
 * Отсюда второе следствие: язык не расходится между устройствами. Так и
 * задумано — телефон по-английски и компьютер по-русски это нормально,
 * а «телефон переключился сам» — нет.
 *
 * Ключ через двоеточие, а не под `mypri/`: под тем префиксом лежит запасная
 * копия данных, и keys() в store/local/db.ts вернул бы язык как ключ данных —
 * он уехал бы в копию и попал под сброс. Прецедент — `devkit:outbox`.
 *
 * Модуль лежит в platform/ по той же причине, что и session.ts: ответ у
 * платформ разный, и в сборке под Capacitor подменится только он. От
 * sessionStore отличается контрактом — здесь всё синхронно, иначе незачем.
 */

const KEY = 'mypri:lang';

export function readLanguage(): string | undefined {
  try {
    return localStorage.getItem(KEY) ?? undefined;
  } catch {
    // Доступ к самому объекту бросает в приватном режиме Safari.
    return undefined;
  }
}

export function saveLanguage(code: string): void {
  try {
    localStorage.setItem(KEY, code);
  } catch {
    /* приватный режим или запрет хранилища: выбор доживёт до конца сеанса */
  }
}
