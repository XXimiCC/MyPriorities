-- Откуда пришёл человек: метка из ссылки, по которой он открыл приложение.
--
-- Одна колонка вместо таблицы: у профиля источник ровно один и меняться он не
-- может по определению — «откуда пришёл» бывает только в прошедшем времени.
--
-- Заполняется единственный раз, при создании профиля (worker/src/auth.ts).
-- Существующие профили остаются с null навсегда, и это не пробел, а честный
-- ответ: человек, который завёл профиль до появления метки, пришёл не по
-- сегодняшней ссылке, и записать ему её задним числом значило бы приписать
-- каталогу чужого пользователя.
--
-- Читается ночным отчётом (worker/src/report.ts) — там она печатается разбивкой
-- по каналам. Запросом то же самое:
--
--   select source, count(*) from profiles where source is not null group by source;
--
-- Индекса нет намеренно: профилей на порядки меньше, чем операций, и полный
-- проход раз в сутки дешевле лишней структуры на записи.
alter table profiles add column source text;
