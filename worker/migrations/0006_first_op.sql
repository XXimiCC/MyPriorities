-- Момент первой записи в профиле.
--
-- Единственный признак во всей базе, который нельзя восстановить задним числом.
-- Свёртка (`src/compact.ts`) складывает операции старше двух недель в месячные
-- снимки и удаляет строки из `ops`; снимок хранит день, к которому операция
-- относится, но не момент, когда она пришла. Вместе со строками навсегда
-- исчезает `min(ops.created_at)` — единственный след того, сколько дней прошло
-- от появления профиля до первой записи в нём.
--
-- Возвращаемость, ритм и дни с отметками восстанавливаются из снимков когда
-- угодно и поэтому ждут. Этот — либо будет записан до первой свёртки, либо не
-- будет никогда.
--
-- Колонка nullable намеренно: «ещё не записал ни разу» — это состояние, в
-- котором профиль живёт от входа до первой операции, а иногда и навсегда. Ноль
-- или дата входа на его месте были бы неотличимы от настоящей записи.
alter table profiles add column first_op_at text;

-- Разовый догон: у кого строки в журнале ещё живы, отметка берётся из них.
--
-- Одноразовая работа, а не постоянная: дальше отметку ставит приём операций
-- (`src/sync.ts`). Тем, у кого журнал уже свёрнут, взять её неоткуда — они
-- останутся с null, и это честнее выдуманной даты.
update profiles
   set first_op_at = (select min(created_at) from ops where ops.user_id = profiles.user_id)
 where first_op_at is null
   and exists (select 1 from ops where ops.user_id = profiles.user_id);
