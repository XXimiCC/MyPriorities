export interface Env {
  DB: D1Database;

  /**
   * Кадры экрана из панели отладки. KV, а не D1: картинка в строке базы съела
   * бы суточную квоту на записанные байты, а здесь ещё и срок хранения встроен.
   */
  SHOTS: KVNamespace;

  /**
   * Версия развёртывания от Cloudflare. Локально привязки нет, и это нормально:
   * там «что развёрнуто» не вопрос.
   */
  CF_VERSION?: { id: string; tag?: string; timestamp?: string };

  /** Список origin через запятую. Пустой — браузерных клиентов не пускаем вовсе. */
  ALLOWED_ORIGINS: string;

  /** Токен бота. Только секрет Worker, в репозитории его нет и быть не должно. */
  TELEGRAM_BOT_TOKEN: string;
  /** Ключ подписи наших токенов. Тоже секрет. */
  JWT_SECRET: string;

  /**
   * Клиент входа через Telegram вне мини-аппа. Идентификатор совпадает с
   * номером бота и не тайна; секрет — отдельная от токена бота пара, и он тайна.
   */
  TELEGRAM_CLIENT_ID?: string;
  TELEGRAM_OAUTH_CLIENT_SECRET?: string;
  /** Кому слать ночной отчёт. Не задан — отчёт молча пропускается. */
  REPORT_CHAT_ID?: string;

  /**
   * Кто может присылать тикеты из встроенной панели: номера Telegram через
   * запятую. Не задан — не может никто, и это правильное умолчание.
   */
  DEVKIT_ALLOW?: string;
  /**
   * Ключ командной строки: им `npm run tickets:pull` доказывает, что это свои.
   * Секрет. В бандл приложения не попадает никогда — там другая дверь.
   */
  DEVKIT_TOKEN?: string;
  /**
   * Ключ из ссылки для приглашённых тестировщиков. Не задан — тикеты шлют
   * только те, кто в DEVKIT_ALLOW.
   *
   * Слабее белого списка намеренно: ключ живёт в ссылке, а ссылку
   * пересылают. Он открывает ровно одно — право завести тикет со своего
   * аккаунта Telegram; сменить его — это `wrangler secret put` и новая ссылка.
   */
  DEVKIT_INVITE?: string;
}
