/**
 * Что делать по какому расписанию.
 *
 * Расписаний у Worker теперь два, а обработчик `scheduled` — один на все: какое
 * из них сработало, известно только по `event.cron`. Пока расписание было одно,
 * поле можно было не смотреть; со вторым это уже не деталь, а развилка, и она
 * живёт здесь, рядом с текстом напоминания, а не растекается по точке входа.
 *
 * Напоминание — двухнедельная проверка идеи на самом владельце (MYPR-33): одно
 * сообщение в фиксированный час на тот же чат, куда приходит ночной отчёт.
 * Никаких подписок, тумблеров и отписки — они появятся только если через две
 * недели фраза всё ещё будет возвращать в приложение.
 */

import type { Env } from './env';
import { sendMessage } from './telegram';

/** Ночная уборка и отчёт. Совпадает с первой строкой crons в wrangler.toml. */
export const NIGHTLY_CRON = '0 3 * * *';
/** Ежедневное напоминание. Совпадает со второй строкой crons в wrangler.toml. */
export const REMINDER_CRON = '0 18 * * *';

/**
 * Текст напоминания. Только по-русски: сообщение уходит на REPORT_CHAT_ID, это
 * не строка интерфейса, и требование двух локалей на него не распространяется.
 */
export const REMINDER_TEXT = 'Не забыл отметить приоритеты, над которыми работал?';

export type Job = 'nightly' | 'reminder';

/**
 * Какое дело стоит за расписанием.
 *
 * Всё, кроме напоминания, — ночная уборка: так вело себя расписание до второго
 * триггера, и локальный запуск `/__scheduled` без параметра `cron` (пустая
 * строка) попадает туда же. Ошибиться в сторону уборки безопасно, в сторону
 * напоминания — значит написать человеку в три часа ночи.
 */
export function jobFor(cron: string): Job {
  return cron === REMINDER_CRON ? 'reminder' : 'nightly';
}

/**
 * Одна отправка напоминания. Тот же договор, что у ночного отчёта: не задан
 * адресат — молча ничего не делаем, отказ доставки ничего не роняет.
 *
 * Пропущенный запуск не догоняется намеренно: напоминание в 23:40 вместо 21:00
 * хуже неприсланного.
 */
export async function sendReminder(env: Env): Promise<void> {
  if (!env.REPORT_CHAT_ID) return;
  const sent = await sendMessage(env.TELEGRAM_BOT_TOKEN, env.REPORT_CHAT_ID, REMINDER_TEXT);
  if (!sent) console.warn('[remind] напоминание не ушло');
}
